

USE ECOM;


create table CUSOMERS(
CUST_ID varchar(255),
FIRST_NAME varchar(250),
LAST_NAME varchar(255),
EMAIL varchar(250),
GENDER enum("MALE","FEMALE","OTHERS"),
PHONE varchar(10),
ANNUAL_INCOME DECIMAL(10,2));
SELECT * 
FROM CUSOMERS; 

describe CUSOMERS;
create table products(
PROD_ID INT PRIMARY KEY,
PROD_NAME VARCHAR(255) UNIQUE,
UNIT_PRICE DECIMAL (10,2),
CATEGORY VARCHAR(200));

ALTER TABLE CUSOMERS
modify COLUMN CUST_ID VARCHAR(255) PRIMARY KEY;

DESCRIBE CUSOMERS;

CREATE TABLE SALES(
QUANTITY INT,
SALES DECIMAL (9,2),
CUST_ID varchar(200),
PROD_ID INT,
DISCOUNT DECIMAL(3,2),
LOCATION CHAR(50),
ORDER_DATE DATE, 
DELIVERY_DATE DATE, 
PROFIT DECIMAL(9,2));

ALTER TABLE SALES
ADD CONSTRAINT FOREIGN KEY (CUST_ID) REFERENCES CUSOMERS(CUST_ID),
ADD constraint foreign key (PROD_ID) references products(PROD_ID);

